    <h2>3. Показники</h2>
    <p>Головне чесне число — <b>золотий набір</b>: 120 сніпетів, розмічених людиною вручну (збалансований). Модель
        навчали <b>без</b> цих відповідей і оцінювали за людськими мітками.</p>
    <div class="scroll">
    <table>
        <thead><tr><th>Модель</th><th class="num">Macro-F1 (золотий набір)</th><th class="num">Recall «негативно»</th></tr></thead>
        <tbody>
        <tr><td>TF-IDF</td><td class="num">0.43</td><td class="num">0.14</td></tr>
        <tr><td>Ембединги</td><td class="num">0.46</td><td class="num">0.14</td></tr>
        <tr><td>Fine-tuned (зерна 1, 2, 3, 42)</td><td class="num">0.53–0.62 (середнє 0.58)</td>
            <td class="num">0.32–0.43 (середнє 0.39)</td></tr>
        </tbody>
    </table>
    </div>
    <ul>
        <li><b>Macro-F1</b> — середня якість по трьох класах (від 0 до 1), усі класи мають однакову вагу.
            <b>Recall «негативно»</b> — яку частку справжніх негативів модель знайшла.</li>
        <li>Точність для «негативно» висока (≈ 0.78): що модель назвала негативом, зазвичай справді негатив. Але повнота
            низька: у найкращому запуску (зерно 2) знайдено ≈ 41% із 37 негативів золотого набору (precision 0.83,
            recall 0.41).</li>
        <li>Лише зерно зсуває macro-F1 fine-tuned моделі приблизно на 9 пунктів, тож одному запуску довіряти не можна.</li>
    </ul>

    <h2>4. Як це рахувалось</h2>
    <ul>
        <li><b>Дані.</b> <code>data/labels/stance.csv</code>: 1621 рядок. Із них 982 — справжні сніпети з міткою Claude,
            639 — синтетичні (ідентифікатори ≥ 100000), і вони лише «рекомендує» або «негативно», ніколи «нейтрально».</li>
        <li><b>Крос-валідація за відповідями.</b> Сніпети однієї відповіді схожі між собою, тому 5 фолдів ділять дані за
            <code>response_id</code> (StratifiedGroupKFold): жодна відповідь не потрапляє і в навчання, і в тест. Звичайний
            випадковий поділ пропустив би майже-дублікати з навчання в тест і завищив результат.</li>
        <li><b>Довірчий інтервал.</b> 95% CI для macro-F1 — bootstrap по цілих відповідях (1000 перевибірок).</li>
        <li><b>База для порівняння.</b> «Завжди вгадувати найчастіший клас»: модель має бути кращою за це.</li>
        <li><b>Золотий набір.</b> Модель тренується без 120 людських відповідей і оцінюється лише на них.</li>
        <li><b>Збіг людини з Claude.</b> Cohen's κ = 0.74 [0.62–0.84] на тих самих 120 сніпетах.</li>
        <li><b>Без API.</b> Оцінка не викликає платних моделей:
            <code>uv run python scripts/evaluate_classifier.py --features finetune --seed 42</code>.</li>
    </ul>

    <div class="note"><b>Пастка в цифрах.</b> Об'єднана крос-валідація (≈ 0.80–0.86) завищена через синтетичні рядки, бо
        вони ніколи не «нейтральні». На справжніх рядках macro-F1 для tfidf і embed лише ≈ 0.63, а на людському золотому
        наборі ще нижче. Чесне число — золотий набір.</div>

    <h2>5. Чому ми її не обрали</h2>
    <ol>
        <li><b>Вона слабша за вчителя.</b> Macro-F1 ≈ 0.58 на золотому наборі, і знаходить лише ≈ 39% негативів. Мітки
            Claude збігаються з людськими суттєво (κ = 0.74).</li>
        <li><b>Вона систематично занижує негатив.</b> М'які порівняльні негативи («менш функціональний, ніж X», «немає
            аналога», «старіший на вигляд») вона вважає нейтральними. Саме частка негативу — ключовий показник вкладки
            «Тональність», тож студент спотворив би головний результат.</li>
        <li><b>Вона нічого не додає до цифр.</b> Усі 982 справжні сніпети вже розмічені Claude, у БД лишилось лише 43
            нерозмічених. Масштабувати нікуди.</li>
        <li><b>Результат нестабільний.</b> Зерно рухає якість приблизно на 9 пунктів, а найкращий варіант важить ≈ 330 МБ.</li>
        <li><b>Частину промахів задав сам вчитель.</b> 3 із 17 пропущених негативів випливають із промпта розмітки:
            він називає «нейтральним» «варто, лише якщо…» і чисту різницю в ціні чи архітектурі, а людина ставила
            «негативно». Студент не може бути кращим за мітки, на яких вчиться.</li>
    </ol>

    <h2>6. Що можна покращити</h2>
    <ul>
        <li>Вирішити політику розмітки: чи вважати «гірше або дорожче за фактами» негативом без явної критики. Зміна
            означає перерозмітку, а це гроші.</li>
        <li>Показувати крос-валідацію на справжніх рядках окремо, щоб об'єднаний результат не сприймали за якість.</li>
        <li>Зібрати більше справжніх даних новим опитуванням: нерозмічених сніпетів майже не лишилось.</li>
    </ul>

