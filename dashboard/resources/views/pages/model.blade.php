    <h2>Власна модель тональності («студент»)</h2>
    <p class="muted">Знімок результатів від 2026-10-12 (джерело: <code>docs/stance_classifier.md</code>). Цифри
        статичні: після нового навчання їх треба оновити вручну.</p>

    <h2>1. Для чого вона</h2>
    <p>Підрахунок згадок бренду не каже, <b>як</b> його згадали: «Stripe — найкращий вибір» і «уникайте Stripe для X»
        рахуються як одна згадка. Модель додає тональність: кожна згадка бренду отримує мітку «рекомендує»,
        «нейтрально» або «негативно».</p>
    <p>Claude розмічає сніпети добре, але платно й повільно. Ідея була така: Claude («вчитель») розмічає частину
        даних один раз, а дешева локальна модель («студент») вчиться на цих мітках і розмічає решту безкоштовно й
        відтворювано.</p>

    <h2>2. Що вона робить</h2>
    <ol>
        <li><b>Сніпети.</b> Навколо кожної згадки бренду вирізається коротке вікно речень. Мітка належить парі
            «бренд, сніпет», бо одна відповідь може по-різному ставитись до різних брендів.</li>
        <li><b>Маскування.</b> Назва бренду, про який питаємо, замінюється на <code>TARGETBRAND</code>, інші бренди — на
            <code>OTHERBRAND</code>, щоб модель не вчила «Stripe — це добре», а дивилась на слова навколо.</li>
        <li><b>Розмітка вчителем.</b> Claude ставить мітки пачками (потрібен явний бюджет).</li>
        <li><b>Навчання.</b> Студент вчиться на цих мітках. Запуски, метрики й моделі логуються в MLflow.</li>
        <li><b>Сервіс.</b> FastAPI завантажує зареєстровану модель і повертає мітки для нових текстів.</li>
    </ol>

