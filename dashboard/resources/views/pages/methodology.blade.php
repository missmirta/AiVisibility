    <h2>Що вимірюємо</h2>
    <p>Частота згадки бренду у відповідях AI — статистична оцінка, а не фіксоване число: модель відповідає на те саме
        питання по-різному. Тому кожна оцінка тут має bootstrap-довірчий інтервал, а «зміна» вважається шумом, якщо
        інтервали перетинаються.</p>

    <h3>Правило «шум, якщо інтервали перетинаються»</h3>
    <ul>
        <li>Було 40% (інтервал 35–45%), стало 44% (інтервал 39–49%). Інтервали накладаються, тож різниця могла
            виникнути випадково. Це шум.</li>
        <li>Було 40% (35–45%), стало 60% (55–65%). Інтервали не перетинаються, тож зміна, імовірно, справжня.</li>
    </ul>
    <p>Це груба перевірка. Інтервали можуть трохи перетинатись, а різниця все одно бути
        реальною, тому правило консервативне. Для початку воно просте і зрозуміле.</p>

    <p>Методологічна основа — Sielinski,
        <a href="https://arxiv.org/abs/2603.08924">arXiv:2603.08924</a>.
        Див. також дослідження SparkToro про непослідовність AI-рекомендацій брендів:
        <a href="https://sparktoro.com/blog/new-research-ais-are-highly-inconsistent-when-recommending-brands-or-products-marketers-should-take-care-when-tracking-ai-visibility/">SparkToro</a>.</p>

    <h2>Як рахується</h2>
    <ul>
        <li><b>Видимість:</b> частка відповідей зі згадкою бренду, bootstrap по відповідях (1000 перетасовок).</li>
        <li><b>Збіжність:</b> ширина CI на підвибірках різного розміру з уже зібраних відповідей.</li>
        <li><b>Карта сприйняття:</b> попарні порівняння «A чи B?» в обох порядках, модель Bradley-Terry, bootstrap по
            комірках (пара брендів × контекст).</li>
        <li><b>Репрезентативність:</b> класифікатор відрізняє синтетичні запити від реальних (AUC, permutation-тест),
            кластери тем дають ваги, зважений bootstrap показує, як рухається частка згадок.
            <p><b>AUC</b> показує, наскільки добре класифікатор розрізняє два класи: 0.5 — вгадування навмання
                (запити не відрізнити), 1.0 — ідеальне розділення. <b>Permutation-тест</b> перевіряє, чи AUC міг
                вийти випадково: мітки «синтетичний / реальний» багато разів перемішуються, AUC рахується заново,
                а p — це частка перемішувань, де AUC не менший за справжній. Малий p означає, що вибірки справді
                різні й потрібне перезважування.</p></li>
        <li><b>Адаптивний семплінг:</b> офлайн-симуляція на вже зібраних відповідях; порівнюємо розподіл запитів
            «рівномірно» і «туди, де CI найширший». Довірчий інтервал — по повторах симуляції.</li>
        <li><b>Тональність:</b> частка сніпетів «рекомендує / нейтрально / негативно» (мітки Claude); bootstrap по
            відповідях, бо сніпети однієї відповіді залежні.</li>
        <li>Уся статистика рахується в Python; цей дашборд лише показує експортований JSON.</li>
    </ul>

    <h2>Обмеження</h2>
    <ul>
        <li>Це що модель каже, а не що правда; фактичну точність (комісії, країни) не перевіряли.</li>
        <li>Малий пілот: 2 бренди для частки згадок, 4 — для карти сприйняття, n = 24–36 відповідей на групу.</li>
        <li>Чисті chatbot-відповіді без retrieval: це не Google AI Overview чи Perplexity.</li>
        <li>Немає довгих часових рядів; порівняння «двох періодів» — демонстрація методу.</li>
        <li>Детекція згадок — пошук підрядка, без NER.</li>
        <li>Температура й seed API не контролюються: повторний прогін дасть трохи інші числа.</li>
        <li>Мітки тональності — судження Claude, не істина; узгодженість з людиною показана на сторінці «Тональність».</li>
        <li>CI адаптивного семплінгу не враховує, що пул відповідей скінченний.</li>
    </ul>
